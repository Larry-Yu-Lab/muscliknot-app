// Helper to validate language code
export const isSupportedLanguage = (lang: string): lang is Language => {
    return LANGUAGES.some(l => l.code === lang);
};

export const getTranslation = (lang: Language, key: keyof typeof translations['en'], params?: Record<string, string>) => {
    // Safety check: if lang is not in translations, fallback to en
    const targetLang = translations[lang] ? lang : 'en';
    const translation = translations[targetLang] as Record<string, string>;
    const fallback = translations['en'] as Record<string, string>;

    let result = translation[key] || fallback[key] || key;
    result = String(result || '');

    // Handle template variables like ${name}
    if (params) {
        Object.entries(params).forEach(([k, v]) => {
            result = result.replace(`\${${k}}`, v);
        });
    }

    return result;
};

/**
 * Formats a raw key or string (snake_case or camelCase) into properly formatted Title Case.
 * Example: "appleHealth" -> "Apple Health", "deltoid_front" -> "Deltoid Front"
 */
export const formatLabel = (str: string): string => {
    if (!str) return '';
    // Split by underscores, spaces, or before capital letters
    return str
        .split(/[_\s]|(?=[A-Z])/)
        .filter(Boolean)
        .map(word => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
        .join(' ');
};
